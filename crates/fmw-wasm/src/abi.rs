    /// A Fulgora request is still 104 bytes, which is what v1's was.
    ///
    /// Not a coincidence worth relying on, but worth pinning: it means the
    /// v2 split cost Fulgora nothing, and if someone later "tidies" the common
    /// prefix this says so.
    ///
    /// **A Vulcanus request has grown twice with no version bump** - 304 -> 336
    /// when the cliff view landed, 336 -> 368 when the rock and resource
    /// overlays did. That is what a per-planet block is FOR: the prefix
    /// declares its own length, `BadParamsLength` refuses a writer that
    /// disagrees, and Fulgora's request has not moved a byte through either.
    /// The two halves ship together and
    /// `test/fixtures/wasm-request.v2.json` pins the encoding, so there is no
    /// third party to keep compatible.
    #[test]
    fn the_split_left_a_fulgora_request_the_size_it_was_in_v1() {
        assert_eq!(COMMON_BYTES + FULGORA_PARAMS_BYTES, 104);
        assert_eq!(COMMON_BYTES + VULCANUS_PARAMS_BYTES, 368);
        assert_eq!(REQUEST_BYTES, 368);
    }

    /// Each failure mode has its OWN code, so a caller can tell "you sent an
    /// old version" from "you sent nothing".
    #[test]
    fn every_rejection_has_its_own_status() {
        assert_eq!(decode(&[]), Err(Status::ShortBuffer));
        assert_eq!(decode(&[0u8; COMMON_BYTES - 1]), Err(Status::ShortBuffer));

        let mut b = good_fulgora();
        b[0] ^= 0xff;
        assert_eq!(decode(&b), Err(Status::BadMagic));

        let mut b = good_fulgora();
        b[4..8].copy_from_slice(&(ABI_VERSION + 1).to_le_bytes());
        assert_eq!(decode(&b), Err(Status::BadVersion));

        let mut b = good_fulgora();
        b[8..12].copy_from_slice(&99u32.to_le_bytes());
        assert_eq!(decode(&b), Err(Status::UnsupportedPlanetOrView));

        // A declared length that is not this planet's.
        let mut b = good_fulgora();
        b[28..32].copy_from_slice(&(FULGORA_PARAMS_BYTES as u32 + 8).to_le_bytes());
        assert_eq!(decode(&b), Err(Status::BadParamsLength));

        // v1's writer sent a zero in that slot. Under v2 it would fail on the
        // version word first, but if only the length word were stale this is
        // what it looks like.
        let mut b = good_fulgora();
        b[28..32].copy_from_slice(&0u32.to_le_bytes());
        assert_eq!(decode(&b), Err(Status::BadParamsLength));
    }

    /// The Vulcanus planet code with a correctly declared but ABSENT block is a
