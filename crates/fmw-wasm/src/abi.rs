    /// The same for Vulcanus's 39 fields, which is where a duplicated offset is
    /// most likely and least visible.
    ///
    /// A distinct value into every slot, all read back - so a pair of fields
    /// sharing an offset shows up as two equal values where the input had none.
    /// The two boxes are adjacent and the same shape, which is exactly the pair
    /// most likely to be wired to one another.
    #[test]
    fn no_two_vulcanus_fields_share_an_offset() {
        let mut b = good_vulcanus();
        // 39 distinct values: 11 scalars, 20 trig components, 8 box edges.
        for i in 0..39 {
            let at = COMMON_BYTES + i * 8;
            let v = 100.0f64 + i as f64;
            b[at..at + 8].copy_from_slice(&v.to_le_bytes());
        }
        let r = decode(&b).expect("should decode");
        let Params::Vulcanus(v) = r.params else {
            panic!("wrong block")
        };
        let mut got = vec![
            v.volcanism_frequency,
            v.volcanism_size,
            v.temperature_bias,
            v.tungsten_frequency,
            v.tungsten_size,
            v.coal_frequency,
            v.coal_size,
            v.calcite_frequency,
            v.calcite_size,
            v.sulfur_frequency,
            v.sulfur_size,
        ];
        for (sin, cos) in v.trig {
            got.push(sin);
            got.push(cos);
        }
        got.extend_from_slice(&v.cell_query_box);
        got.extend_from_slice(&v.placement_sweep_box);
        let want: Vec<f64> = (0..39).map(|i| 100.0 + i as f64).collect();
        assert_eq!(got, want);
    }

    /// The ten bearings are addressed by NAME, and the names map to the slots
    /// the layout table says.
    ///
    /// Two bearings swapped rotates the planet's biomes and produces a map that
    /// looks entirely reasonable, so this is checked directly rather than left
    /// to a render comparison.
    #[test]
    fn each_bearing_reads_its_own_pair() {
        let mut b = good_vulcanus();
        for i in 0..VULCANUS_BEARINGS {
            let at = COMMON_BYTES + 88 + i * 16;
            b[at..at + 8].copy_from_slice(&(i as f64).to_le_bytes());
            b[at + 8..at + 16].copy_from_slice(&(-(i as f64)).to_le_bytes());
        }
        let Params::Vulcanus(v) = decode(&b).expect("should decode").params else {
            panic!("wrong block")
        };
        for (i, which) in [
            VulcanusBearing::SpawnAshlands,
            VulcanusBearing::SpawnMountains,
            VulcanusBearing::SpawnBasalts,
            VulcanusBearing::BiomeVolcanoSpot,
            VulcanusBearing::BiomeProtector,
            VulcanusBearing::ResourceTungsten,
            VulcanusBearing::ResourceCoal,
            VulcanusBearing::ResourceCalcite,
            VulcanusBearing::ResourceSulfurFar,
            VulcanusBearing::ResourceSulfurNear,
        ]
        .into_iter()
        .enumerate()
        {
            assert_eq!(v.bearing(which), (i as f64, -(i as f64)), "{which:?}");
        }
    }
