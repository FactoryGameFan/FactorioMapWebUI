/**
 * Aquilo's real surface - land, water and every placed entity - read out of
 * the game, for replaying the per-chunk entity stream (#492).
 *
 *   node --experimental-strip-types scripts/probes/aquilo-entity-stream/capture.ts
 *
 * Run from the repository root. It runs both installs below through
 * `factorio-oracle` and writes
 * `test/fixtures/oracle-aquilo-surface.seed123456.json`. Read `README.md` beside
 * this file for what it found.
 *
 * The planet's own surface with its DERIVED seed (map seed 123456, so
 * 3111923328) at default levers. The wells' `created_effect` rewrites tiles near
 * them during map generation, and the stream must be replayed on the tiles
 * BEFORE that rewrite, so the effect is removed in data-final-fixes (the
 * "stripped arm" of `scripts/probes/aquilo-fields`). Chunks -8..8 are
 * requested and forced; then every tile over -320..319 is read, every chunk in
 * -10..9 is asked whether it was generated, and every `resource` and
 * `simple-entity` on the surface is listed with no area filter.
 *
 * A real surface runs tile correction, which the preview's resolver does not,
 * so the fixture stores the game's own land/water layout as run lengths per
 * row. The entity list inside tiles -256..255 must equal the census in
 * `test/fixtures/oracle-aquilo-entities.seed123456.json`, and every install
 * must return the same land, chunks and entities, or nothing is written.
 */
import { execFile } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const ORACLE = join(process.env.HOME ?? "", ".cargo", "bin", "factorio-oracle");
const OUT = join(REPO, "test", "fixtures", "oracle-aquilo-surface.seed123456.json");
const CENSUS = join(REPO, "test", "fixtures", "oracle-aquilo-entities.seed123456.json");

/** The first install is the primary; the rest must match it exactly. */
const INSTALLS = [
  {
    root: "/home/eric/Projects/factorio-oracle/installs/factorio-headless-2.1.23/factorio",
    version: "2.1.23",
  },
  { root: "/home/eric/factorio-headless-2.0.77", version: "2.0.77" },
] as const;
type Install = (typeof INSTALLS)[number];

const MAP_SEED = 123456;
/** 123456 + crc32("aquilo"), as planet-autoplace asserts it. */
const DERIVED_SEED = 3111923328;
const CHUNK_RADIUS = 8;
/** Tiles read: x and y in X0 .. X0 + SIZE - 1. Chunks -10..9. */
const X0 = -320;
const SIZE = 640;
const CHUNK_LO = X0 / 32;
const CHUNK_HI = (X0 + SIZE) / 32 - 1;
/** The census fixture's region, tiles -256..255. */
const CENSUS_LO = -256;
const CENSUS_HI = 255;

const CONTROL_NAMES = ["aquilo_crude_oil", "lithium_brine", "fluorine_vent"] as const;

/** Every tile the window may hold, in fixture order. The first six are land. */
const TILE_LEGEND = [
  "snow-flat",
  "snow-crests",
  "snow-lumpy",
  "snow-patchy",
  "ice-rough",
  "ice-smooth",
  "brash-ice",
  "ammoniacal-ocean",
  "ammoniacal-ocean-2",
] as const;
const LAND = new Set<string>(TILE_LEGEND.slice(0, 6));

// ---------------------------------------------------------------------------
// The Lua.
// ---------------------------------------------------------------------------

const DATA_LUA = `-- GENERATED by scripts/probes/aquilo-entity-stream/capture.ts.
for _, n in ipairs({"crude-oil", "lithium-brine", "fluorine-vent"}) do data.raw.resource[n].created_effect = nil end
`;

function controlLua(): string {
  return `-- GENERATED by scripts/probes/aquilo-entity-stream/capture.ts.
local X0, SIZE = ${String(X0)}, ${String(SIZE)}
local CLO, CHI = ${String(CHUNK_LO)}, ${String(CHUNK_HI)}
local CLO2, CHI2 = ${String(CENSUS_LO)}, ${String(CENSUS_HI)}
script.on_init(function()
  assert(script.active_mods["space-age"], "space-age is not loaded")
  local s = game.planets["aquilo"].create_surface()
  local mgs = s.map_gen_settings
  local controls = {}
  for _, n in ipairs({ ${CONTROL_NAMES.map((n) => JSON.stringify(n)).join(", ")} }) do
    local c = mgs.autoplace_controls[n]
    controls[n] = c and { frequency = c.frequency, size = c.size, richness = c.richness } or false
  end
  s.request_to_generate_chunks({ 0, 0 }, ${String(CHUNK_RADIUS)})
  s.force_generate_chunk_requests()
  -- Each row as runs of tile names: name, count, name, count, ...
  local rows = {}
  for y = X0, X0 + SIZE - 1 do
    local row, last, n = {}, nil, 0
    for x = X0, X0 + SIZE - 1 do
      local t = s.get_tile(x, y).name
      if t == last then
        n = n + 1
      else
        if last then row[#row + 1] = last; row[#row + 1] = n end
        last, n = t, 1
      end
    end
    row[#row + 1] = last; row[#row + 1] = n
    rows[#rows + 1] = row
  end
  local chunks = {}
  for cy = CLO, CHI do
    for cx = CLO, CHI do
      if s.is_chunk_generated({ cx, cy }) then chunks[#chunks + 1] = { cx, cy } end
    end
  end
  local list = {}
  for _, e in ipairs(s.find_entities_filtered({ type = { "resource", "simple-entity" } })) do
    list[#list + 1] = {
      name = e.name, x = e.position.x, y = e.position.y,
      amount = (e.type == "resource") and e.amount or false,
    }
  end
  -- The census's own query, area filter and all, for the cross-check.
  local area = {}
  for _, e in ipairs(s.find_entities_filtered({ type = { "resource", "simple-entity" }, area = { { CLO2, CLO2 }, { CHI2 + 1, CHI2 + 1 } } })) do
    area[#area + 1] = {
      name = e.name, x = e.position.x, y = e.position.y,
      amount = (e.type == "resource") and e.amount or false,
    }
  end
  helpers.write_file("oracle-dump.json", helpers.table_to_json({
    seed = mgs.seed, controls = controls, rows = rows, chunks = chunks, entities = list, censusArea = area,
  }))
  error("DUMPED-OK")
end)
`;
}

// ---------------------------------------------------------------------------
// Running the game.
// ---------------------------------------------------------------------------

async function runOracle(install: Install): Promise<{ buildLine: string; dump: unknown }> {
  const dir = await mkdtemp(join(tmpdir(), "aquilo-entity-stream-"));
  try {
    await writeFile(join(dir, "control.lua"), controlLua());
    const probePath = join(dir, "probe.json");
    await writeFile(
      probePath,
      JSON.stringify({
        mode: "create",
        mod: {
          name: "aquilo_entity_stream_probe",
          version: "0.0.1",
          dependencies: ["base", "space-age"],
          control_lua_file: join(dir, "control.lua"),
          data_final_fixes_lua: DATA_LUA,
        },
        seed: MAP_SEED,
        timeout_seconds: 1800,
      }),
    );
    const workDir = join(dir, "work");
    // A successful run throws (DUMPED-OK); keep the error as the cause.
    let oracleError: unknown;
    let stdout = "";
    try {
      const r = await run(
        ORACLE,
        [
          "run",
          "--probe",
          probePath,
          "--work-dir",
          workDir,
          "--factorio",
          install.root,
          "--version",
          install.version,
        ],
        { maxBuffer: 256 * 1024 * 1024 },
      );
      stdout = r.stdout;
    } catch (e) {
      oracleError = e;
      stdout = (e as { stdout?: string }).stdout ?? "";
    }
    let report: { provenance?: { buildLine?: string } } = {};
    try {
      report = JSON.parse(stdout) as typeof report;
    } catch {
      // The buildLine check below names the failure.
    }
    const buildLine = report.provenance?.buildLine ?? "";
    let text: string;
    try {
      text = await readFile(join(workDir, "write", "script-output", "oracle-dump.json"), "utf8");
    } catch (e) {
      throw new Error(`${install.version}: no dump`, { cause: oracleError ?? e });
    }
    // Without --version a bad path silently runs another install with exit 0.
    if (!buildLine.includes(`Version: ${install.version} `)) {
      throw new Error(`ran "${buildLine}", wanted ${install.version}`, { cause: oracleError });
    }
    return { buildLine, dump: JSON.parse(text) };
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

// ---------------------------------------------------------------------------
// Reading the dump.
// ---------------------------------------------------------------------------

interface Lever {
  frequency: number;
  size: number;
  richness: number;
}
interface Entity {
  name: string;
  x: number;
  y: number;
  amount: number | false;
}
interface Dump {
  seed: number;
  controls: Record<string, Lever | false>;
  rows: (string | number)[][];
  chunks: [number, number][];
  entities: Entity[];
  censusArea: Entity[];
}
interface Surface {
  version: string;
  buildLine: string;
  land: number[][];
  tileCounts: Record<string, number>;
  chunks: [number, number][];
  entities: Entity[];
  /** The census's own area query, which matches by bounding box. */
  censusArea: Entity[];
}

const byPosition = (a: Entity, b: Entity): number =>
  a.name < b.name ? -1 : a.name > b.name ? 1 : a.x !== b.x ? a.x - b.x : a.y - b.y;

/**
 * One row of name runs to water/land runs, starting with water. Asserts every
 * name is in the legend and the runs cover the row.
 */
function landRuns(row: (string | number)[], y: number, counts: Record<string, number>): number[] {
  const out: number[] = [];
  let land = false;
  let run = 0;
  let total = 0;
  for (let i = 0; i < row.length; i += 2) {
    const name = row[i];
    const n = row[i + 1];
    if (typeof name !== "string" || typeof n !== "number") {
      throw new Error(`row ${String(y)}: bad run at ${String(i)}`);
    }
    if (!(TILE_LEGEND as readonly string[]).includes(name)) {
      throw new Error(`row ${String(y)}: tile "${name}" is not in the legend`);
    }
    counts[name] = (counts[name] ?? 0) + n;
    total += n;
    if (LAND.has(name) === land) {
      run += n;
    } else {
      out.push(run);
      land = !land;
      run = n;
    }
  }
  out.push(run);
  if (total !== SIZE) throw new Error(`row ${String(y)}: runs sum to ${String(total)}`);
  if (out.reduce((a, b) => a + b, 0) !== SIZE) throw new Error(`row ${String(y)}: land runs`);
  return out;
}

async function capture(install: Install): Promise<Surface> {
  const { buildLine, dump } = await runOracle(install);
  const d = dump as Dump;
  if (d.seed !== DERIVED_SEED) {
    throw new Error(`surface seed ${String(d.seed)}, wanted ${String(DERIVED_SEED)}`);
  }
  for (const n of CONTROL_NAMES) {
    const c = d.controls[n];
    if (!c || c.frequency !== 1 || c.size !== 1 || c.richness !== 1) {
      throw new Error(`${n} reads ${JSON.stringify(c)}, wanted 1/1/1`);
    }
  }
  if (d.rows.length !== SIZE) throw new Error(`${String(d.rows.length)} rows came back`);
  const tileCounts: Record<string, number> = {};
  const land = d.rows.map((row, i) => landRuns(row, X0 + i, tileCounts));
  const chunks = [...d.chunks].sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  const entities = [...d.entities].sort(byPosition);
  const censusArea = [...d.censusArea].sort(byPosition);
  return { version: install.version, buildLine, land, tileCounts, chunks, entities, censusArea };
}

function tally<T>(xs: T[], key: (x: T) => string): Record<string, number> {
  const out: Record<string, number> = {};
  for (const x of xs) out[key(x)] = (out[key(x)] ?? 0) + 1;
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => (a < b ? -1 : 1)));
}

/** The census entities, as [name, x, y, amount], in its own order. */
async function censusEntities(): Promise<[string, number, number, number | false][]> {
  const c = JSON.parse(await readFile(CENSUS, "utf8")) as {
    surfaceSeed: number;
    region: [number, number];
    entities: [string, number, number, string, string, number | false][];
  };
  if (c.surfaceSeed !== DERIVED_SEED || c.region[0] !== CENSUS_LO || c.region[1] !== CENSUS_HI) {
    throw new Error("the census fixture is not the region this script expects");
  }
  return c.entities.map((e) => [e[0], e[1], e[2], e[5]]);
}

const inCensus = (e: Entity): boolean =>
  e.x >= CENSUS_LO && e.x < CENSUS_HI + 1 && e.y >= CENSUS_LO && e.y < CENSUS_HI + 1;

