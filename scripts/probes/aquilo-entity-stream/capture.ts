// Main.
// ---------------------------------------------------------------------------

const shortBuild = (b: string): string => b.replace(/^Version: /, "");

async function main(): Promise<void> {
  const surfaces: Surface[] = [];
  for (const install of INSTALLS) {
    const s = await capture(install);
    console.log(
      `${s.buildLine}: ${String(s.entities.length)} entities, ${String(s.chunks.length)} chunks generated`,
    );
    surfaces.push(s);
  }
  const [p, ...others] = surfaces;

  // Every install must agree: land, chunks, entities (with amounts).
  const crossChecked: Record<string, string> = {};
  for (const o of others) {
    const diffs: string[] = [];
    if (JSON.stringify(o.land) !== JSON.stringify(p.land)) diffs.push("land");
    if (JSON.stringify(o.tileCounts) !== JSON.stringify(p.tileCounts)) diffs.push("tile counts");
    if (JSON.stringify(o.chunks) !== JSON.stringify(p.chunks)) diffs.push("chunks");
    if (JSON.stringify(o.entities) !== JSON.stringify(p.entities)) diffs.push("entities");
    if (JSON.stringify(o.censusArea) !== JSON.stringify(p.censusArea)) diffs.push("census area");
    if (diffs.length > 0) {
      throw new Error(`${o.version} differs from ${p.version} in: ${diffs.join(", ")}`);
    }
    crossChecked[o.version] =
      "identical (land, tile counts by name, generated chunks, entity names, positions and amounts)";
    console.log(`  ${o.version} vs ${p.version}: ${crossChecked[o.version]}`);
  }

  // The census region, read with the census's own query (an area filter,
  // which matches by bounding box), must be the census, and every one of those
  // entities must be in the full list. Positions inside the region are counted
  // too: an entity can stand outside it and still be found by its box.
  const census = await censusEntities();
  const key = (e: unknown[]): string => JSON.stringify(e);
  const area = p.censusArea.map((e) => [e.name, e.x, e.y, e.amount]);
  if (key(area) !== key(census)) {
    const a = new Set(area.map(key));
    const b = new Set(census.map(key));
    const onlyMine = [...a].filter((k) => !b.has(k));
    const onlyCensus = [...b].filter((k) => !a.has(k));
    throw new Error(
      `the census area query differs from the census:\n` +
        `  only here (${String(onlyMine.length)}): ${onlyMine.slice(0, 10).join(" ")}\n` +
        `  only in census (${String(onlyCensus.length)}): ${onlyCensus.slice(0, 10).join(" ")}`,
    );
  }
  const all = new Set(p.entities.map((e) => key([e.name, e.x, e.y, e.amount])));
  const missing = census.filter((e) => !all.has(key(e)));
  if (missing.length > 0) {
    throw new Error(`census entities missing from the full list: ${missing.map(key).join(" ")}`);
  }
  const inside = p.entities.filter(inCensus);
  const outsideButFound = p.censusArea.filter((e) => !inCensus(e));
  console.log(
    `  census area query: ${String(p.censusArea.length)} entities, identical to the census (names, positions, amounts), all in the full list`,
  );
  console.log(
    `  ${String(inside.length)} of ${String(p.entities.length)} entities stand inside tiles ${String(CENSUS_LO)}..${String(CENSUS_HI)}; found by box from outside: ${JSON.stringify(outsideButFound)}`,
  );

  const totals = tally(p.entities, (e) => e.name);
  const landTiles = Object.entries(p.tileCounts)
    .filter(([n]) => LAND.has(n))
    .reduce((a, [, n]) => a + n, 0);
  console.log(`  totals ${JSON.stringify(totals)}`);
  console.log(`  tiles ${JSON.stringify(p.tileCounts)}; land ${String(landTiles)}`);

  const comment =
    `Ground truth from Factorio ${shortBuild(p.buildLine)}: game.planets["aquilo"].create_surface() with its ` +
    `DERIVED seed ${String(DERIVED_SEED)} (map seed ${String(MAP_SEED)}, read back) and the three resource controls ` +
    `read back as 1/1/1. This is the STRIPPED arm: created_effect is removed from crude-oil, lithium-brine and ` +
    `fluorine-vent in data-final-fixes, so the tiles are the ones the entity stream saw, before the wells' tile ` +
    `rewrite. request_to_generate_chunks({0,0}, ${String(CHUNK_RADIUS)}) then force_generate_chunk_requests(). ` +
    `\`land\`: surface.get_tile(x, y).name for every tile of \`window\`, one entry per row from y = ${String(X0)} ` +
    `down, as run lengths alternating WATER, LAND, WATER, ... starting with water (a row that starts on land ` +
    `begins with 0); land is the first six names of \`tileLegend\`, water the last three; each row sums to ` +
    `${String(SIZE)}, and every tile read was a legend name. \`generatedChunks\`: every [cx, cy] in ` +
    `${String(CHUNK_LO)}..${String(CHUNK_HI)} where surface.is_chunk_generated is true. \`entities\`: every ` +
    `resource and simple-entity on the surface (no area filter) as [name, x, y], sorted by name, x, y. Those inside ` +
    `tiles ${String(CENSUS_LO)}..${String(CENSUS_HI)} by the census's own query (an area filter, which matches by ` +
    `bounding box, so it finds ${String(p.censusArea.length)} while ${String(inside.length)} positions lie inside) were ` +
    `asserted equal (names, positions, amounts) to oracle-aquilo-entities.seed123456.json, and each is in this ` +
    `list. Cross-checked: ` +
    `${others.map((o) => `${shortBuild(o.buildLine)} ${crossChecked[o.version]}`).join("; ")}. ` +
    `Captured by scripts/probes/aquilo-entity-stream.`;

  const lines = [
    "{",
    `  "_comment": ${JSON.stringify(comment)},`,
    `  "_factorioVersion": ${JSON.stringify(p.version)},`,
    `  "_buildLines": ${JSON.stringify(surfaces.map((s) => s.buildLine))},`,
    `  "_crossChecked": ${JSON.stringify(crossChecked)},`,
    `  "mapSeed": ${String(MAP_SEED)},`,
    `  "surfaceSeed": ${String(DERIVED_SEED)},`,
    `  "chunkRadius": ${String(CHUNK_RADIUS)},`,
    `  "window": ${JSON.stringify({ x0: X0, y0: X0, width: SIZE, height: SIZE })},`,
    `  "tileLegend": ${JSON.stringify(TILE_LEGEND)},`,
    `  "tileCounts": ${JSON.stringify(Object.fromEntries(TILE_LEGEND.map((t) => [t, p.tileCounts[t] ?? 0])))},`,
    `  "totals": ${JSON.stringify(totals)},`,
    `  "generatedChunks": ${JSON.stringify(p.chunks)},`,
    '  "land": [',
    ...p.land.map((r, i) => `    ${JSON.stringify(r)}${i < p.land.length - 1 ? "," : ""}`),
    "  ],",
    '  "entities": [',
    ...p.entities.map(
      (e, i) => `    ${JSON.stringify([e.name, e.x, e.y])}${i < p.entities.length - 1 ? "," : ""}`,
    ),
    "  ]",
    "}",
    "",
  ];
  await writeFile(OUT, lines.join("\n"));
  console.log(`wrote ${OUT}`);
}

await main();
