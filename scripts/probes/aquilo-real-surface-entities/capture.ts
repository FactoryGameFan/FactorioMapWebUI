/**
 * Every well and iceberg on a REAL Aquilo surface over the app's default
 * window, for grading the engine's Aquilo entity overlays (#553).
 *
 *   node --experimental-strip-types scripts/probes/aquilo-real-surface-entities/capture.ts
 *
 * Run from the repository root. It starts Factorio 2.1.23 twice through
 * `factorio-oracle` and writes
 * `test/fixtures/oracle-aquilo-real-surface-entities.seed123456.json`. Read
 * `README.md` beside this file for what it found.
 *
 * ## What it reads
 *
 * Map seed 123456 and Aquilo's own `create_surface()`, so the surface seed is
 * the derived 3111923328, with the three resource controls at their default
 * (read back as 1/1/1). One `request_to_generate_chunks` around chunk (0, 0)
 * covers the window -512..511 and a two-chunk margin, the way a game start
 * asks for its spawn area. Then every resource and simple-entity whose tile,
 * `floor(position)`, lies in the window or within `RING` tiles of it is
 * listed at its exact position, and the script refuses to write if any other
 * name is there.
 *
 * ## The two arms
 *
 * - `shipped`: no data-stage mod. The map a player gets. Its entities are
 *   what the fixture records.
 * - `stripped`: `created_effect` removed from the three wells in
 *   data-final-fixes, so no well rewrites the tiles near it. Its entity list
 *   must equal the shipped arm's, or nothing is written: the rewrite must not
 *   move an entity, because the engine does not draw it.
 *
 * Both arms read `get_tile` at every tile of the window. The tiles that
 * differ between the arms are the rewrite's footprint, counted into
 * `wellTileRewrite`; the tiles themselves are not kept.
 */
import { execFile } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const ORACLE = join(process.env.HOME ?? "", ".cargo", "bin", "factorio-oracle");
const OUT =
  process.env.FMW_OUT ??
  join(REPO, "test", "fixtures", "oracle-aquilo-real-surface-entities.seed123456.json");
const INSTALL = {
  root: process.env.FMW_FACTORIO_2_1_23 ?? "/home/eric/factorio-headless/2.1.23/factorio",
  version: "2.1.23",
};

const MAP_SEED = 123456;
/** 123456 + crc32("aquilo"). */
const DERIVED_SEED = 3111923328;
/** The window: tiles X0 .. X0 + SIDE - 1 on both axes. Chunk aligned. */
const X0 = -512;
const SIDE = 1024;
const MARGIN_CHUNKS = 2;
/**
 * Entities listed past the window's edge, in tiles: a huge iceberg's box
 * reaches 1.85 tiles from its position, so one whose tile is up to 2 tiles
 * out can cover a window tile.
 */
const RING = 3;

const NAMES = [
  "crude-oil",
  "fluorine-vent",
  "lithium-brine",
  "lithium-iceberg-big",
  "lithium-iceberg-huge",
] as const;
const WELLS = new Set<string>(["crude-oil", "fluorine-vent", "lithium-brine"]);
const CONTROL_NAMES = ["aquilo_crude_oil", "lithium_brine", "fluorine_vent"] as const;

type Arm = "shipped" | "stripped";

const DATA_LUA = `-- GENERATED by scripts/probes/aquilo-real-surface-entities/capture.ts.
for _, n in ipairs({"crude-oil", "lithium-brine", "fluorine-vent"}) do data.raw.resource[n].created_effect = nil end
`;

function controlLua(): string {
  return `-- GENERATED by scripts/probes/aquilo-real-surface-entities/capture.ts.
local X0, SIDE, MARGIN, RING = ${String(X0)}, ${String(SIDE)}, ${String(MARGIN_CHUNKS)}, ${String(RING)}
script.on_init(function()
  assert(script.active_mods["space-age"], "space-age is not loaded")
  local s = game.planets["aquilo"].create_surface()
  local mgs = s.map_gen_settings
  local controls = {}
  for _, n in ipairs({ ${CONTROL_NAMES.map((n) => JSON.stringify(n)).join(", ")} }) do
    local c = mgs.autoplace_controls[n]
    controls[n] = c and { frequency = c.frequency, size = c.size, richness = c.richness } or false
  end
  local c0, c1 = math.floor(X0 / 32) - MARGIN, math.floor((X0 + SIDE - 1) / 32) + MARGIN
  local pregenerated = 0
  for cy = c0, c1 do
    for cx = c0, c1 do
      if s.is_chunk_generated({ cx, cy }) then pregenerated = pregenerated + 1 end
    end
  end
  s.request_to_generate_chunks({ x = 16, y = 16 }, math.max(-c0, c1))
  s.force_generate_chunk_requests()
  local generated = {}
  for cy = c0 - 2, c1 + 2 do
    for cx = c0 - 2, c1 + 2 do
      if s.is_chunk_generated({ cx, cy }) then generated[#generated + 1] = { cx, cy } end
    end
  end
  local lo, hi = X0 - RING, X0 + SIDE + RING
  local entities, others = {}, {}
  for _, e in pairs(s.find_entities_filtered({ area = { { lo - 8, lo - 8 }, { hi + 8, hi + 8 } }, type = { "resource", "simple-entity" } })) do
    local tx, ty = math.floor(e.position.x), math.floor(e.position.y)
    if tx >= lo and tx < hi and ty >= lo and ty < hi then
      entities[#entities + 1] = { e.name, e.position.x, e.position.y }
    end
  end
  -- Anything else in the window: the census must be the five names.
  for _, e in pairs(s.find_entities_filtered({ area = { { X0, X0 }, { X0 + SIDE, X0 + SIDE } } })) do
    others[e.type .. ":" .. e.name] = (others[e.type .. ":" .. e.name] or 0) + 1
  end
  -- Every tile of the window, each row as runs: name, count, name, count, ...
  local rows = {}
  for y = X0, X0 + SIDE - 1 do
    local row, last, n = {}, nil, 0
    for x = X0, X0 + SIDE - 1 do
      local t = s.get_tile(x, y).name
      if t == last then
        n = n + 1
      else
        if last then row[#row + 1] = last; row[#row + 1] = n end
        last, n = t, 1
      end
    end
    row[#row + 1] = last; row[#row + 1] = n
    rows[#rows + 1] = row
  end
  helpers.write_file("oracle-dump.json", helpers.table_to_json({
    seed = mgs.seed, controls = controls, pregenerated = pregenerated, generated = generated,
    entities = entities, others = others, rows = rows,
  }))
  error("DUMPED-OK")
end)
`;
}

async function runOracle(arm: Arm): Promise<{ buildLine: string; dump: unknown }> {
  const dir = await mkdtemp(join(tmpdir(), "aquilo-real-surface-entities-"));
  try {
    await writeFile(join(dir, "control.lua"), controlLua());
    const probePath = join(dir, "probe.json");
    await writeFile(
      probePath,
      JSON.stringify({
        mode: "create",
        mod: {
          name: "aquilo_real_surface_entities_probe",
          version: "0.0.1",
          dependencies: ["base", "space-age"],
          control_lua_file: join(dir, "control.lua"),
          ...(arm === "stripped" ? { data_final_fixes_lua: DATA_LUA } : {}),
        },
        seed: MAP_SEED,
        timeout_seconds: 1800,
      }),
    );
    const workDir = join(dir, "work");
    // A successful run throws (DUMPED-OK); keep the error as the cause.
    let oracleError: unknown;
    let stdout = "";
    try {
      const r = await run(
        ORACLE,
        [
          "run",
          "--probe",
          probePath,
          "--work-dir",
          workDir,
          "--factorio",
          INSTALL.root,
          "--version",
          INSTALL.version,
        ],
        { maxBuffer: 256 * 1024 * 1024 },
      );
      stdout = r.stdout;
    } catch (e) {
      oracleError = e;
      stdout = (e as { stdout?: string }).stdout ?? "";
    }
    let report: { provenance?: { buildLine?: string } } = {};
    try {
      report = JSON.parse(stdout) as typeof report;
    } catch {
      // The buildLine check below names the failure.
    }
    const buildLine = report.provenance?.buildLine ?? "";
    let text: string;
    try {
      text = await readFile(join(workDir, "write", "script-output", "oracle-dump.json"), "utf8");
    } catch (e) {
      throw new Error(`${arm}: no dump`, { cause: oracleError ?? e });
    }
    // Without --version a bad path silently runs another install with exit 0.
    if (!buildLine.includes(`Version: ${INSTALL.version} `)) {
      throw new Error(`ran "${buildLine}", wanted ${INSTALL.version}`, { cause: oracleError });
    }
    return { buildLine, dump: JSON.parse(text) };
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

interface Lever {
  frequency: number;
  size: number;
  richness: number;
}
interface Dump {
  seed: number;
  controls: Record<string, Lever | false>;
  pregenerated: number;
  generated: [number, number][];
  entities: [string, number, number][];
  others: Record<string, number>;
  rows: (string | number)[][];
}

/** One arm's window as a tile name per tile, row-major. */
function tilesOf(rows: (string | number)[][]): string[] {
  if (rows.length !== SIDE) throw new Error(`${String(rows.length)} rows came back`);
  const out: string[] = [];
  for (const row of rows) {
    const start = out.length;
    for (let i = 0; i < row.length; i += 2) {
      const name = row[i];
      const n = row[i + 1];
      if (typeof name !== "string" || typeof n !== "number") throw new Error("bad run");
      for (let k = 0; k < n; k++) out.push(name);
    }
    if (out.length - start !== SIDE) throw new Error("a row's runs do not cover it");
  }
  return out;
}

const byPosition = (a: [string, number, number], b: [string, number, number]): number =>
  a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : a[1] !== b[1] ? a[1] - b[1] : a[2] - b[2];

async function capture(arm: Arm): Promise<{ buildLine: string; d: Dump }> {
  const { buildLine, dump } = await runOracle(arm);
  const d = dump as Dump;
  if (d.seed !== DERIVED_SEED) {
    throw new Error(`${arm}: surface seed ${String(d.seed)}, wanted ${String(DERIVED_SEED)}`);
  }
  for (const n of CONTROL_NAMES) {
    const c = d.controls[n];
    if (!c || c.frequency !== 1 || c.size !== 1 || c.richness !== 1) {
      throw new Error(`${arm}: ${n} reads ${JSON.stringify(c)}, wanted 1/1/1`);
    }
  }
  if (d.pregenerated !== 0)
    throw new Error(`${arm}: ${String(d.pregenerated)} chunks pregenerated`);
  for (const e of d.entities) {
    if (!(NAMES as readonly string[]).includes(e[0])) throw new Error(`${arm}: unexpected ${e[0]}`);
  }
  // Explosions are the wells' created_effect; nothing else may stand there.
  for (const k of Object.keys(d.others)) {
    const [type, name] = k.split(":");
    const known =
      (NAMES as readonly string[]).includes(name ?? "") ||
      (type === "explosion" && /^aquilo-tiles-(inner|outer)-explosion$/.test(name ?? ""));
    if (!known) throw new Error(`${arm}: unexpected entity ${k} in the window`);
  }
  d.entities.sort(byPosition);
  d.generated.sort((a, b) => a[1] - b[1] || a[0] - b[0]);
  return { buildLine, d };
}

async function main(): Promise<void> {
  const shipped = await capture("shipped");
  const stripped = await capture("stripped");
  console.log(
    `${shipped.buildLine}: ${String(shipped.d.entities.length)} entities, ${String(shipped.d.generated.length)} chunks generated`,
  );
  if (JSON.stringify(shipped.d.entities) !== JSON.stringify(stripped.d.entities)) {
    throw new Error("the stripped arm places different entities");
  }
  if (JSON.stringify(shipped.d.generated) !== JSON.stringify(stripped.d.generated)) {
    throw new Error("the stripped arm generated different chunks");
  }
  // The rewrite's footprint: tiles that differ between the arms, each with
  // its Chebyshev distance to the nearest well's tile, and whether a well's
  // 3 x 3 footprint covers it.
  const a = tilesOf(shipped.d.rows);
  const b = tilesOf(stripped.d.rows);
  const wellTiles = shipped.d.entities
    .filter((e) => WELLS.has(e[0]))
    .map((e) => [Math.floor(e[1]), Math.floor(e[2])] as const);
  let rewritten = 0;
  let uncovered = 0;
  let farthest = 0;
  for (let i = 0; i < SIDE * SIDE; i++) {
    if (a[i] === b[i]) continue;
    rewritten++;
    const x = X0 + (i % SIDE);
    const y = X0 + Math.floor(i / SIDE);
    let near = Infinity;
    for (const [wx, wy] of wellTiles)
      near = Math.min(near, Math.max(Math.abs(x - wx), Math.abs(y - wy)));
    farthest = Math.max(farthest, near);
    if (near > 1) uncovered++;
  }
  const wells = wellTiles.length;
  const inWindow = shipped.d.entities.filter(
    (e) =>
      Math.floor(e[1]) >= X0 &&
      Math.floor(e[1]) < X0 + SIDE &&
      Math.floor(e[2]) >= X0 &&
      Math.floor(e[2]) < X0 + SIDE,
  );
  const totals: Record<string, number> = {};
  for (const e of inWindow) totals[e[0]] = (totals[e[0]] ?? 0) + 1;
  console.log(`  in the window: ${JSON.stringify(totals)}`);
  console.log(
    `  well tile rewrite: ${String(rewritten)} tiles of the window, ${String(uncovered)} outside every well's 3 x 3, farthest ${String(farthest)} tiles from a well's tile (${String(wells)} wells within the ring)`,
  );
  for (const w of WELLS) if (!(w in totals)) throw new Error(`no ${w} in the window`);

  const about =
    "Every well and iceberg on a REAL Aquilo surface (game.planets.aquilo.create_surface(), derived seed " +
    `${String(DERIVED_SEED)} for map seed ${String(MAP_SEED)}, read back; aquilo_crude_oil, lithium_brine and ` +
    "fluorine_vent read back as 1/1/1; no chunk generated before the request), after ONE " +
    `request_to_generate_chunks({16, 16}, ${String(-(Math.floor(X0 / 32) - MARGIN_CHUNKS))}) and ` +
    "force_generate_chunk_requests. `entities`: every resource and simple-entity whose floor(position) lies in " +
    `tiles ${String(X0 - RING)}..${String(X0 + SIDE + RING - 1)} (the window ${String(X0)}..${String(X0 + SIDE - 1)} ` +
    `and ${String(RING)} tiles past it) as [name, x, y], sorted by name, x, y; the window held no other entity ` +
    "but the wells' aquilo-tiles explosions. `generatedChunks`: every [cx, cy] is_chunk_generated reports, " +
    "row-major. A second run with created_effect removed from the three wells in data-final-fixes placed the " +
    "same entities and generated the same chunks; `wellTileRewrite` counts the window's tiles whose get_tile " +
    "name differs between the two runs (`tiles`), how many of those lie outside every well's 3 x 3 footprint " +
    "(`outsideWellFootprints`), and the farthest such tile from a well's tile (Chebyshev, `farthest`). " +
    "Written by scripts/probes/aquilo-real-surface-entities/capture.ts.";

  const lines = [
    "{",
    `  "about": ${JSON.stringify(about)},`,
    `  "buildLine": ${JSON.stringify(shipped.buildLine)},`,
    `  "mapSeed": ${String(MAP_SEED)},`,
    `  "surfaceSeed": ${String(DERIVED_SEED)},`,
    `  "window": ${JSON.stringify({ x0: X0, y0: X0, width: SIDE, height: SIDE })},`,
    `  "ring": ${String(RING)},`,
    `  "totals": ${JSON.stringify(totals)},`,
    `  "wellTileRewrite": ${JSON.stringify({ tiles: rewritten, outsideWellFootprints: uncovered, farthest })},`,
    `  "generatedChunks": ${JSON.stringify(shipped.d.generated)},`,
    '  "entities": [',
    ...shipped.d.entities.map(
      (e, i) => `    ${JSON.stringify(e)}${i < shipped.d.entities.length - 1 ? "," : ""}`,
    ),
    "  ]",
    "}",
    "",
  ];
  await writeFile(OUT, lines.join("\n"));
  console.log(`wrote ${OUT}`);
}

await main();
