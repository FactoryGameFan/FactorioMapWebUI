/**
 * Capture `basis_noise` at points where one half of a corner's dot product is
 * exactly zero, so the near-zero gradient slots can be graded (#455).
 *
 * Run deliberately, never in CI - it needs a local Factorio install and it
 * writes a committed fixture:
 *
 *   node --experimental-strip-types scripts/probes/basis-axis/capture.ts \
 *     [<cross-check install> <its version>]
 *
 * The first run is the installed Steam build. The optional pair names a second
 * install, for example
 * `~/GitHub/factorio-oracle/installs/factorio-2.0.77.app 2.0.77`, which
 * is captured the same way and must return bit-identical values or nothing is
 * written. The version is not optional there: factorio-oracle treats
 * `--factorio` as one MORE place to look, and without `--version` the first
 * install it finds - the Steam one - still wins.
 *
 * ## Why these points
 *
 * Four gradient slots are near zero: slot 0's y, slot 64's x, slot 128's y and
 * slot 192's x, each about 1e-7 against a magnitude of 4.2. Sampled anywhere
 * ordinary, such a component is swamped by the other half of the dot product
 * and the f32 answer carries none of its bits. #234's capture, 1/256 off the
 * lattice, could not pin them for exactly that reason.
 *
 * On a lattice ROW (`dy = 0` exactly) the corner's value is `dx * gx` times the
 * falloff, so if that corner's slot has a near-zero `gx`, the answer is that
 * component to full f32 precision. The only other corner still inside `d < 1`
 * is `(i + 1, j)`, whose term is `~8 * dx^3 * 4.2`; at `dx = 2^-16` that is
 * about 4% of the near term, and its slot is an ordinary one the table already
 * holds exactly. Columns (`dx = 0`) do the same for `gy`.
 *
 * `dx` this small needs the noise coordinate to resolve below the 1/256 tile a
 * `MapPosition` can hold, so the scale does the work: at `input_scale = 2^-8`
 * the world point `(256 i + k/256, 256 j)` is the noise point
 * `(i + k * 2^-16, j)`. Every one of those is exact in f32 and in f64, so the
 * capture does not depend on which precision the game multiplies in.
 *
 * ## Why a sweep rather than aiming at the slots
 *
 * The slot is `sigma[a[i] ^ b[j]]`, and `a` is a permutation, so one row of 256
 * `i` values touches every slot exactly once. Sweeping whole rows needs no
 * table on the Lua side and hands the scorer every OTHER slot at the same
 * geometry as a control: those were pinned by #234 and must stay exact.
 *
 * ## The cases
 *
 * Four expressions with different seeds, routed to Nauvis's four climate
 * properties so one `calculate_tile_properties` call reads them all. One uses
 * `2^-7` and one `2^-9`, so the same world points land on other corners and
 * other `dx`; at `2^-9` the odd `i` sit half a cell out and grade nothing,
 * which is fine, since they are scored the same way as everything else.
 *
 * This reaches the game's POINT kernel. The gradient table is shared with the
 * chunk-grid kernel, which is how #451's grid fixture found the same two slots.
 */

import { execFile } from "node:child_process";
import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { homedir, tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { promisify } from "node:util";

const run = promisify(execFile);

const ORACLE = join(homedir(), ".cargo", "bin", "factorio-oracle");
const ROOT = resolve(import.meta.dirname, "..", "..", "..");
const FIXTURE = join(ROOT, "test", "fixtures", "oracle-basis-axis.json");

/** One source for what a case IS: the Lua, the fixture and the scorer all read it. */
const CASES = [
  { property: "elevation", seed0: 123456, seed1: 0, inputScale: 2 ** -8 },
  { property: "moisture", seed0: 123456, seed1: 5, inputScale: 2 ** -8 },
  { property: "aux", seed0: 2967702466, seed1: 77, inputScale: 2 ** -7 },
  { property: "temperature", seed0: 1000003, seed1: 200, inputScale: 2 ** -9 },
] as const;

const ROWS = 4;
const OFFSETS = [1, 3] as const;

function dataLua(): string {
  const entries = CASES.map(
    (c) => `  {
    type = "noise-expression",
    name = "probe_axis_${c.property}",
    expression = "basis_noise{x = x, y = y, seed0 = ${c.seed0}, seed1 = ${c.seed1}, input_scale = ${c.inputScale}, output_scale = 1}",
  },`,
  ).join("\n");
  return `-- GENERATED by scripts/probes/basis-axis/capture.ts. Do not edit.\ndata:extend({\n${entries}\n})\n`;
}

/**
 * `error("DUMPED-OK")` makes Factorio exit non-zero on a SUCCESSFUL run; the
 * dump file appearing is the real check. `script.on_init` is registered once.
 */
function controlLua(): string {
  const props = CASES.map((c) => JSON.stringify(c.property)).join(", ");
  return `-- GENERATED by scripts/probes/basis-axis/capture.ts. Do not edit.
local ROWS = ${ROWS}
local OFFSETS = { ${OFFSETS.join(", ")} }
local PROPS = { ${props} }

local function sample()
    local surface = game.surfaces[1]
    local positions = {}
    for j = 0, ROWS - 1 do
        for i = 0, 255 do
            for _, k in ipairs(OFFSETS) do
                positions[#positions + 1] = { x = 256 * i + k / 256, y = 256 * j }
                positions[#positions + 1] = { x = 256 * i, y = 256 * j + k / 256 }
            end
        end
    end
    -- A control that can fail: on a lattice point every corner offset is
    -- zero, so the game must return exactly 0 whatever the table holds.
    -- Multiples of 512, because 256 is only a lattice step at the two larger
    -- scales: at 2^-9 an odd multiple of 256 is half a cell out, and the first
    -- run of this probe returned 1.0099 there.
    for j = 0, 3 do
        for i = 0, 3 do
            positions[#positions + 1] = { x = 512 * i, y = 512 * j }
        end
    end

    local props = surface.calculate_tile_properties(PROPS, positions)
    local xs, ys = {}, {}
    for n, p in ipairs(positions) do
        xs[n] = p.x
        ys[n] = p.y
    end
    local out = { x = xs, y = ys, values = {} }
    for _, name in ipairs(PROPS) do
        out.values[name] = props[name]
    end
    helpers.write_file("oracle-dump.json", helpers.table_to_json(out))
    error("DUMPED-OK")
end

script.on_init(sample)
`;
}

interface Dump {
  x: number[];
  y: number[];
  values: Record<string, number[]>;
}

async function capture(install?: {
  path: string;
  version: string;
}): Promise<{ dump: Dump; build: string }> {
  const dir = await mkdtemp(join(tmpdir(), "basis-axis-"));
  const controlPath = join(dir, "control.lua");
  const probePath = join(dir, "probe.json");
  await writeFile(controlPath, controlLua());
  await writeFile(
    probePath,
    JSON.stringify({
      mode: "create",
      mod: {
        name: "basis_axis_probe",
        version: "0.0.1",
        dependencies: ["base"],
        control_lua_file: controlPath,
        data_lua: dataLua(),
      },
      seed: 123456,
      map_gen_settings: {
        property_expression_names: Object.fromEntries(
          CASES.map((c) => [c.property, `probe_axis_${c.property}`]),
        ),
      },
      timeout_seconds: 300,
    }),
  );
  const workDir = join(dir, "work");
  const select =
    install === undefined ? [] : ["--factorio", install.path, "--version", install.version];
  let log = "";
  try {
    const r = await run(ORACLE, ["run", "--probe", probePath, "--work-dir", workDir, ...select], {
      maxBuffer: 256 * 1024 * 1024,
    });
    log = r.stdout + r.stderr;
  } catch (e) {
    // Expected: see the DUMPED-OK note above.
    const err = e as { stdout?: string; stderr?: string };
    log = (err.stdout ?? "") + (err.stderr ?? "");
  }
  const dumpPath = join(workDir, "write", "script-output", "oracle-dump.json");
  let text: string;
  try {
    text = await readFile(dumpPath, "utf8");
  } catch {
    throw new Error(`no dump at ${dumpPath}. oracle output tail:\n${log.slice(-3000)}`);
  }
  const build = /Version: [^\n"]*\)/.exec(log)?.[0] ?? "unknown build";
  return { dump: JSON.parse(text) as Dump, build };
}

/**
 * The lattice control, and every value an f32 - checked, not assumed.
 *
 * `helpers.table_to_json` prints most values as their exact decimal, but not
 * all: measured on 2.1.20, 2 of 32,800 came back with 16 significant digits,
 * one unit off in the 17th, and both were tiny on-axis values - the very ones
 * this capture exists for. Sixteen digits still name exactly one f32 (an f32
 * needs nine), so each value is rounded to f32 here and refused unless it was
 * already within print error of it, far below one f32 ulp.
 */
function check(dump: Dump, build: string): void {
  const n = dump.x.length;
  const sweep = ROWS * 256 * OFFSETS.length * 2;
  if (n !== sweep + 16) throw new Error(`${build}: ${n} positions, expected ${sweep + 16}`);
  for (const c of CASES) {
    const v = dump.values[c.property];
    if (v?.length !== n) throw new Error(`${build}: ${c.property} has ${v?.length} values`);
    for (let p = 0; p < n; p++) {
      const f = Math.fround(v[p]!);
      if (Math.abs(f - v[p]!) > Math.abs(f) * 1e-15) {
        throw new Error(`${build}: ${c.property}[${p}] = ${v[p]} is not an f32`);
      }
      v[p] = f;
    }
    for (let p = sweep; p < n; p++) {
      if (v[p] !== 0) throw new Error(`${build}: ${c.property} is ${v[p]} on a lattice point`);
    }
  }
}

const crossCheck =
  process.argv[2] === undefined
    ? undefined
    : { path: process.argv[2], version: process.argv[3] ?? "" };
if (crossCheck?.version === "") throw new Error("a cross-check install needs its version too");
const primary = await capture();
check(primary.dump, primary.build);
console.log(
  `captured ${primary.dump.x.length} points x ${CASES.length} cases from ${primary.build}`,
);

let crossBuild: string | undefined;
if (crossCheck !== undefined) {
  const other = await capture(crossCheck);
  // factorio-oracle given a `--factorio` path that does not exist runs the
  // DEFAULT install instead and exits 0 (measured 2026-10-18, after the
  // 2.0.77 copy had lost its data folder). The two builds "agreeing" would then be one
  // build agreeing with itself, so a cross-check that names the primary's own
  // build line is refused.
  if (other.build === primary.build) {
    throw new Error(
      `the cross-check ran ${other.build} again - is ${crossCheck.path} a real install?`,
    );
  }
  check(other.dump, other.build);
  if (JSON.stringify(other.dump) !== JSON.stringify(primary.dump)) {
    throw new Error(`${other.build} disagrees with ${primary.build}; nothing written`);
  }
  crossBuild = other.build;
  console.log(`cross-check: ${other.build} returned bit-identical values`);
}

const fixture = {
  _comment:
    `Ground truth from Factorio's POINT basis_noise kernel through calculate_tile_properties, ${primary.build}. ` +
    "Points sit on lattice rows (noise dy = 0) or columns (noise dx = 0), a tiny step off a corner, so a corner whose " +
    "gradient slot has a near-zero component returns that component to full f32 precision (#455). x[n], y[n] are " +
    "WORLD positions; the noise point is (x * inputScale, y * inputScale), exact in f32 and f64. Each case's values[n] " +
    "is basis_noise at point n, output_scale 1. The last 16 points are lattice points at every case's scale and must be exactly 0. " +
    (crossBuild === undefined
      ? "Not cross-checked. "
      : `Cross-checked: ${crossBuild} returned bit-identical values. `) +
    "Captured by scripts/probes/basis-axis/capture.ts.",
  cases: CASES.map((c) => ({ ...c, values: primary.dump.values[c.property] })),
  x: primary.dump.x,
  y: primary.dump.y,
};
await writeFile(FIXTURE, JSON.stringify(fixture) + "\n");
console.log(`wrote ${FIXTURE}`);
