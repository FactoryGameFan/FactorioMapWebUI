"""Chain probe: for many map seeds, ask the game for the Vulcanus-style bearings.

Each seed gets its own surface (game.create_surface with that seed). The noise
expressions copy the Vulcanus definitions in planet-vulcanus-map-gen.lua, so the
game's own f32 values come back: map_seed_normalized, the direction, the
ashlands, mountains, basalts and protector angles, and sin/cos of the basalts
and protector bearings.
"""
import json, os, random, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "probe3")
os.makedirs(OUT, exist_ok=True)
rng = random.Random(7531)
seeds = [rng.randint(0, 2**32 - 1) for _ in range(600)]
seeds += [0, 1, 2, 2**32 - 1, 16777217, 4294967295 - 1]   # edge seeds

control = "-- Generated by make_chain_probe.py\nlocal seeds = {" + ",".join(str(s) for s in seeds) + "}\n" + """
local function collect()
  local rows = {}
  for i, s in ipairs(seeds) do
    local surface = game.create_surface("fmw_probe_" .. i, {seed = s})
    local p = surface.calculate_tile_properties(
      {"probe_msn", "probe_dir", "probe_ash", "probe_mtn", "probe_bas",
       "probe_prot_deg", "probe_bas_sin", "probe_bas_cos", "probe_prot_sin", "probe_prot_cos", "probe_fg_deg", "probe_fg_sin"},
      {{x = 0, y = 0}})
    rows[i] = {seed = s,
      msn = p.probe_msn[1], dir = p.probe_dir[1], ash = p.probe_ash[1],
      mtn = p.probe_mtn[1], bas = p.probe_bas[1], prot_deg = p.probe_prot_deg[1],
      bas_sin = p.probe_bas_sin[1], bas_cos = p.probe_bas_cos[1],
      prot_sin = p.probe_prot_sin[1], prot_cos = p.probe_prot_cos[1], fg_deg = p.probe_fg_deg[1], fg_sin = p.probe_fg_sin[1]}
  end
  local keys = {"seed", "msn", "dir", "ash", "mtn", "bas", "prot_deg", "bas_sin", "bas_cos", "prot_sin", "prot_cos", "fg_deg", "fg_sin"}
  local parts = {}
  for i, r in ipairs(rows) do
    local fields = {}
    for _, k in ipairs(keys) do fields[#fields + 1] = "\\"" .. k .. "\\":" .. string.format("%.17g", r[k]) end
    parts[#parts + 1] = "{" .. table.concat(fields, ",") .. "}"
  end
  helpers.write_file("oracle-dump.json", "[" .. table.concat(parts, ",") .. "]", false)
end

script.on_init(collect)
"""
control_path = os.path.join(OUT, "control.lua")
open(control_path, "w").write(control)

data_lua = """data:extend({
  {type = "noise-expression", name = "probe_msn", expression = "map_seed_normalized"},
  {type = "noise-expression", name = "probe_dir", expression = "-1 + 2 * (map_seed_small & 1)"},
  {type = "noise-expression", name = "probe_ash", expression = "map_seed_normalized * 3600"},
  {type = "noise-expression", name = "probe_mtn", expression = "probe_ash + 120 * probe_dir"},
  {type = "noise-expression", name = "probe_bas", expression = "probe_ash + 240 * probe_dir"},
  {type = "noise-expression", name = "probe_prot_deg", expression = "probe_mtn + 180 * probe_dir"},
  {type = "noise-expression", name = "probe_bas_sin", expression = "sin(probe_bas / 180 * pi)"},
  {type = "noise-expression", name = "probe_bas_cos", expression = "cos(probe_bas / 180 * pi)"},
  {type = "noise-expression", name = "probe_prot_sin", expression = "sin(probe_prot_deg / 180 * pi)"},
  {type = "noise-expression", name = "probe_prot_cos", expression = "cos(probe_prot_deg / 180 * pi)"},
  {type = "noise-expression", name = "probe_fg_deg", expression = "map_seed / 360"},
  {type = "noise-expression", name = "probe_fg_sin", expression = "sin(map_seed / 360 / 180 * pi)"},
})
"""
spec = {
    "mode": "create",
    "mod": {"name": "fmw_chain_probe3", "version": "0.0.1", "dependencies": ["base"],
            "control_lua_file": control_path, "data_lua": data_lua},
    "seed": 1,
    "timeout_seconds": 900,
}
json.dump(spec, open(os.path.join(OUT, "probe.json"), "w"), indent=2)
print("seeds", len(seeds))
