"""Probe: the game's `enemy_base_probability` and `starting_area_radius` at several
`starting_area` settings, so the port's radius term can be graded against the game.

Usage:
  make_probe.py make  <outdir>               write one probe folder per arm
  make_probe.py merge <workroot> <fixture>   merge the arms' dumps into one fixture

Each arm is a Nauvis save at map seed 123456 with `map_gen_settings.starting_area`
set to one value and every other setting at its default. One
`calculate_tile_properties` call reads two named noise expressions at the
points below:

  rv_sar  =  starting_area_radius
  rv_ebp  =  enemy_base_probability

The points are six rays from the origin, one every 13 tiles out to 520, so the
three radii in play (112.5 for the Death worlds, 300 for 2, 450 for Ribbon world)
each have points on both sides. Every coordinate is a multiple of 1/4, which is
on the 1/256 capture grid. Values are printed with `%.17g`, so they read back as
the exact f32.
"""

import json
import math
import os
import sys

SEED = 123456
# (arm name, starting_area). 0.75 is Death world's and 3 is Ribbon world's value
# in the committed built-in strings; 1 is the control.
ARMS = [("sa0_5", 0.5), ("sa0_75", 0.75), ("sa1", 1), ("sa2", 2), ("sa3", 3), ("sa6", 6)]
ANGLES_DEG = [0, 41, 90, 133, 217, 301]
STEP = 13
MAX_R = 520


def points():
    pts = [(0.25, 0.25)]
    for deg in ANGLES_DEG:
        a = math.radians(deg)
        for r in range(STEP, MAX_R + 1, STEP):
            x = round(r * math.cos(a) * 4) / 4 + 0.25
            y = round(r * math.sin(a) * 4) / 4 + 0.25
            pts.append((x, y))
    return pts


def make(outdir):
    pts = points()
    lua_pts = ",".join("{x=%r,y=%r}" % p for p in pts)
    control = (
        """-- Generated by make_probe.py
local pts = {%s}
local function collect()
  local s = game.surfaces[1]
  local p = s.calculate_tile_properties({"rv_sar", "rv_ebp"}, pts)
  local sar, ebp = {}, {}
  for i = 1, #pts do
    sar[i] = string.format("%%.17g", p.rv_sar[i])
    ebp[i] = string.format("%%.17g", p.rv_ebp[i])
  end
  local m = s.map_gen_settings
  local out = '{"seed":' .. m.seed .. ',"starting_area":' .. string.format("%%.17g", m.starting_area)
    .. ',"sar":[' .. table.concat(sar, ",") .. '],"ebp":[' .. table.concat(ebp, ",") .. ']}'
  helpers.write_file("oracle-dump.json", out, false)
end
script.on_init(collect)
"""
        % lua_pts
    )
    data_lua = (
        "data:extend({\n"
        '  {type = "noise-expression", name = "rv_sar", expression = "starting_area_radius"},\n'
        '  {type = "noise-expression", name = "rv_ebp", expression = "enemy_base_probability"},\n'
        "})\n"
    )
    for name, sa in ARMS:
        d = os.path.join(outdir, name)
        os.makedirs(d, exist_ok=True)
        control_path = os.path.join(d, "control.lua")
        with open(control_path, "w") as f:
            f.write(control)
        spec = {
            "mode": "create",
            "mod": {
                "name": "fmw_enemy_sa_" + name,
                "version": "0.0.1",
                "dependencies": ["base", "space-age"],
                "control_lua_file": control_path,
                "data_lua": data_lua,
            },
            "seed": SEED,
            "timeout_seconds": 600,
            "map_gen_settings": {"starting_area": sa},
        }
        with open(os.path.join(d, "probe.json"), "w") as f:
            json.dump(spec, f, indent=2)
        print("wrote", os.path.join(d, "probe.json"))


def merge(workroot, fixture):
    pts = points()
    cases = []
    for name, sa in ARMS:
        path = os.path.join(workroot, "work-" + name, "write", "script-output", "oracle-dump.json")
        with open(path) as f:
            d = json.load(f)
        assert d["seed"] == SEED and d["starting_area"] == sa, (name, d["seed"], d["starting_area"])
        assert len(d["ebp"]) == len(pts) == len(d["sar"]), name
        cases.append(
            {"startingArea": sa, "startingAreaRadius": d["sar"], "enemyBaseProbability": d["ebp"]}
        )
    out = {
        "_comment": (
            "Ground truth from Factorio 2.1.23 (build 87750, linux64 headless) via "
            "scripts/probes/enemy-starting-area/make_probe.py: the game's "
            "enemy_base_probability and starting_area_radius, read with "
            "calculate_tile_properties at `positions` on a Nauvis save at map seed 123456, once per "
            "map_gen_settings.starting_area in `cases`. Every other setting is at its default, so "
            "the arms differ only in the starting area. Values are the exact f32s the game "
            "returned, NOT edited."
        ),
        "seed0": SEED,
        "positions": [{"x": x, "y": y} for x, y in pts],
        "cases": cases,
    }
    with open(fixture, "w") as f:
        json.dump(out, f, indent=1)
    print("wrote", fixture, len(pts), "positions x", len(cases), "cases")


if __name__ == "__main__":
    cmd = sys.argv[1]
    if cmd == "make":
        make(sys.argv[2])
    elif cmd == "merge":
        merge(sys.argv[2], sys.argv[3])
    else:
        raise SystemExit(__doc__)
