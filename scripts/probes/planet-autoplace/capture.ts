/** Chunks each side of the origin; 8 gives the 512x512 tile region -256..255. */
const CHUNKS = Number(process.env.REGION_CHUNKS ?? 8);
const AQUILO_RESOURCE_CONTROLS = ["aquilo_crude_oil", "lithium_brine", "fluorine_vent"];

const dataFinalFixesLua = (
  stripEffect: boolean,
): string => `-- GENERATED by scripts/probes/planet-autoplace/capture.ts.
-- Which entity prototypes are placed by which control. Read at runtime from mod-data.
local by_control = {}
local resources = {}
for type_name, protos in pairs(data.raw) do
  for name, p in pairs(protos) do
    local a = p.autoplace
    if type(a) == "table" and p.type ~= "tile" and p.type ~= "optimized-decorative" then
      local key = a.control or "(none)"
      by_control[key] = by_control[key] or {}
      table.insert(by_control[key], p.type .. ":" .. name)
    end
  end
end
for _, list in pairs(by_control) do table.sort(list) end
for _, n in ipairs({"crude-oil", "lithium-brine", "fluorine-vent"}) do
  local r = data.raw.resource[n]
  resources[n] = { control = r.autoplace and r.autoplace.control or "", has_created_effect = r.created_effect ~= nil }
end
data:extend({{ type = "mod-data", name = "planet-autoplace-probe", data = { by_control = by_control, resources = resources } }})
${stripEffect ? `for _, n in ipairs({"crude-oil", "lithium-brine", "fluorine-vent"}) do data.raw.resource[n].created_effect = nil end` : ""}
`;

const controlLua = (
  config: unknown,
): string => `-- GENERATED by scripts/probes/planet-autoplace/capture.ts.
local cfg = helpers.json_to_table([==[${JSON.stringify(config)}]==])
local C = cfg.chunks
local LO, HI = -C * 32, C * 32 - 1

local function set_controls(s, names)
  local mgs = s.map_gen_settings
  for _, n in ipairs(names) do mgs.autoplace_controls[n] = { frequency = 1, size = 0, richness = 1 } end
  s.map_gen_settings = mgs
  local back = {}
  for _, n in ipairs(names) do back[n] = s.map_gen_settings.autoplace_controls[n].size end
  return back
end

local function generate(s)
  s.request_to_generate_chunks({ 0, 0 }, C)
  s.force_generate_chunk_requests()
end

local function settings_dump(s)
  local mgs = s.map_gen_settings
  local out = { seed = mgs.seed, controls = {}, cliff_settings = mgs.cliff_settings, autoplace_settings = {} }
  for n, c in pairs(mgs.autoplace_controls) do out.controls[n] = { frequency = c.frequency, size = c.size, richness = c.richness } end
  for cat, v in pairs(mgs.autoplace_settings) do
    local names = {}
    for n in pairs(v.settings) do names[#names + 1] = n end
    table.sort(names)
    out.autoplace_settings[cat] = names
  end
  out.property_expression_names = mgs.property_expression_names
  return out
end

local function counts(s)
  local ents = s.find_entities_filtered({ area = { { LO, LO }, { HI + 1, HI + 1 } } })
  local by_name, by_type = {}, {}
  for _, e in ipairs(ents) do
    by_name[e.name] = (by_name[e.name] or 0) + 1
    by_type[e.type] = (by_type[e.type] or 0) + 1
  end
  return { total = #ents, byName = by_name, byType = by_type }
end

local function read_region(s)
  local t = {}
  for y = LO, HI do
    local row = {}
    for x = LO, HI do row[#row + 1] = s.get_tile(x, y).name end
    t[y] = row
  end
  return t
end
local function at(t, x, y) return t[y][x - LO + 1] end

local function encode(t)
  local palette, index, rows = {}, {}, {}
  for y = LO, HI do
    local chars = {}
    for x = LO, HI do
      local n = at(t, x, y)
      if not index[n] then palette[#palette + 1] = n; index[n] = #palette end
      chars[#chars + 1] = string.char(96 + index[n])
    end
    rows[#rows + 1] = table.concat(chars)
  end
  return { palette = palette, rows = rows }
end

local function well_list(s)
  local out = {}
  for _, e in ipairs(s.find_entities_filtered({ type = "resource", area = { { LO, LO }, { HI + 1, HI + 1 } } })) do
    out[#out + 1] = { e.name, e.position.x, e.position.y }
  end
  table.sort(out, function(a, b) if a[2] ~= b[2] then return a[2] < b[2] end return a[3] < b[3] end)
  return out
end

local function tally(t, key, n) t[key] = (t[key] or 0) + (n or 1) end

local function is_ocean(n) return n:find("ammoniacal%-ocean", 1) ~= nil end

script.on_init(function()
  assert(script.active_mods["space-age"], "space-age is not loaded")
  local out = { chunks = C, region = { LO, HI } }
  if cfg.mode == "noeffect" then
    local a = game.planets["aquilo"].create_surface()
    generate(a)
    out.seed = a.map_gen_settings.seed
    out.counts = counts(a)
    out.wells = well_list(a)
    out.tiles = encode(read_region(a))
    helpers.write_file("oracle-dump.json", helpers.table_to_json(out))
    error("DUMPED-OK")
  end
  local md = prototypes.mod_data["planet-autoplace-probe"].data
  out.byControl = md.by_control
  out.resourcePrototypes = md.resources

  -- (a) Gleba and (b) the Aquilo entity census.
  out.gleba = {}
  for _, v in ipairs({ { "asis", {} }, { "noplants", { "gleba_plants" } }, { "noenemy", { "gleba_enemy_base" } } }) do
    local s = (v[1] == "asis") and game.planets["gleba"].create_surface()
      or game.create_surface("gleba-" .. v[1], game.surfaces["gleba"].map_gen_settings)
    local back = set_controls(s, v[2])
    generate(s)
    out.gleba[v[1]] = { surface = s.name, seed = s.map_gen_settings.seed, zeroed = back, counts = counts(s) }
    if v[1] == "asis" then out.gleba[v[1]].settings = settings_dump(s) end
  end

  -- Aquilo as is.
  local a1 = game.planets["aquilo"].create_surface()
  local base_mgs = a1.map_gen_settings
  local settings1 = settings_dump(a1)
  generate(a1)
  out.aquilo = { seed = a1.map_gen_settings.seed, settings = settings1, counts = counts(a1) }

  -- Aquilo with the three resource controls at size 0, same settings otherwise.
  local a0 = game.create_surface("aquilo-nowells", base_mgs)
  local zeroed = set_controls(a0, cfg.aquiloResourceControls)
  generate(a0)
  out.aquiloNoWells = { seed = a0.map_gen_settings.seed, zeroed = zeroed, counts = counts(a0) }

  -- Tiles.
  local t1, t0 = read_region(a1), read_region(a0)
  out.tilesWithEffect = encode(t1)
  out.wellList = well_list(a1)
  local wells = a1.find_entities_filtered({ type = "resource", area = { { LO, LO }, { HI + 1, HI + 1 } } })
  local near = {}
  local R = 3
  local per = {}
  local ocean_wells, ocean_centre, ice_wells = {}, {}, {}
  local ring_tiles = {}
  for _, e in ipairs(wells) do
    local ex, ey = math.floor(e.position.x), math.floor(e.position.y)
    local any_ocean, any_land = false, false
    for y = ey - R, ey + R do
      for x = ex - R, ex + R do
        if x >= LO and x <= HI and y >= LO and y <= HI then
          near[y * 100000 + x] = true
          local n = at(t1, x, y)
          tally(ring_tiles, e.name .. "|" .. n)
          if is_ocean(n) then any_ocean = true else any_land = true end
        end
      end
    end
    local cn = (ex >= LO and ex <= HI and ey >= LO and ey <= HI) and at(t1, ex, ey) or ""
    tally(per, e.name .. ".wells")
    if any_ocean then tally(ocean_wells, e.name) end
    if is_ocean(cn) then tally(ocean_centre, e.name) end
    if any_land then tally(ice_wells, e.name) end
  end
  local diffNear, diffFar, pairsNear, pairsFar = 0, 0, {}, {}
  local tilesNear = 0
  for _ in pairs(near) do tilesNear = tilesNear + 1 end
  local wellsWithDiff = {}
  for y = LO, HI do
    for x = LO, HI do
      local n1, n0 = at(t1, x, y), at(t0, x, y)
      if n1 ~= n0 then
        if near[y * 100000 + x] then
          diffNear = diffNear + 1
          tally(pairsNear, n0 .. ">" .. n1)
        else
          diffFar = diffFar + 1
          tally(pairsFar, n0 .. ">" .. n1)
        end
      end
    end
  end
  out.wellRewrite = {
    wells = per, wellsWithOceanIn7x7 = ocean_wells, wellsCentredOnOcean = ocean_centre,
    wellsWithNonOceanIn7x7 = ice_wells, nearTileCount = tilesNear,
    tilesBySurfaceUnderWells = ring_tiles,
    diffNear = diffNear, diffFar = diffFar, pairsNear = pairsNear, pairsFar = pairsFar,
  }
  -- Whole-region tile census on each surface, so a diff is read against it.
  local c1, c0 = {}, {}
  for y = LO, HI do for x = LO, HI do tally(c1, at(t1, x, y)); tally(c0, at(t0, x, y)) end end
  out.tileCensus = { withWells = c1, noWells = c0 }

  -- Positive control: create a well by script on the no-wells surface.
  local function find_site(want_ocean, skip)
    for y = LO + 20, HI - 20, 5 do
      for x = LO + 20, HI - 20, 5 do
        if is_ocean(at(t0, x, y)) == want_ocean and not skip[y * 100000 + x] then
          -- Whole 15x15 must be of the wanted kind, so the effect has room.
          local ok = true
          for dy = -7, 7 do for dx = -7, 7 do
            if is_ocean(at(t0, x + dx, y + dy)) ~= want_ocean then ok = false end
          end end
          if ok then return x, y end
        end
      end
    end
  end
  out.positiveControl = {}
  local used = {}
  for _, name in ipairs({ "crude-oil", "lithium-brine", "fluorine-vent" }) do
    for _, want_ocean in ipairs({ false, true }) do
      local x, y = find_site(want_ocean, used)
      local rec = { entity = name, onOcean = want_ocean }
      if x then
        used[y * 100000 + x] = true
        -- Keep later sites away from this one.
        for dy = -20, 20 do for dx = -20, 20 do used[(y + dy) * 100000 + x + dx] = true end end
        rec.site = { x, y }
        local before = {}
        for dy = -7, 7 do for dx = -7, 7 do before[#before + 1] = a0.get_tile(x + dx, y + dy).name end end
        local ok, err = pcall(function()
          return a0.create_entity({ name = name, position = { x + 0.5, y + 0.5 }, amount = 1000, raise_built = false })
        end)
        rec.created = ok and err ~= nil
        if not ok then rec.error = tostring(err) end
        local changed, pairs_ = 0, {}
        local i = 1
        for dy = -7, 7 do for dx = -7, 7 do
          local n = a0.get_tile(x + dx, y + dy).name
          if n ~= before[i] then changed = changed + 1; tally(pairs_, before[i] .. ">" .. n) end
          i = i + 1
        end end
        rec.changedTiles = changed
        rec.pairs = pairs_
      else
        rec.site = false
      end
      table.insert(out.positiveControl, rec)
    end
  end
  helpers.write_file("oracle-dump.json", helpers.table_to_json(out))
  error("DUMPED-OK")
end)
`;

// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Dump = any;

async function runOracle(mode: "full" | "noeffect"): Promise<{ d: Dump; buildLine: string }> {
  const dir = await mkdtemp(join(tmpdir(), `planet-autoplace-${mode}-`));
  try {
    const controlPath = join(dir, "control.lua");
    await writeFile(
      controlPath,
      controlLua({ mode, chunks: CHUNKS, aquiloResourceControls: AQUILO_RESOURCE_CONTROLS }),
    );
    const probePath = join(dir, "probe.json");
    await writeFile(
      probePath,
      JSON.stringify({
        mode: "create",
        mod: {
          name: "planet_autoplace_probe",
          version: "0.0.1",
          dependencies: ["base", "space-age"],
          control_lua_file: controlPath,
          data_final_fixes_lua: dataFinalFixesLua(mode === "noeffect"),
        },
        seed: MAP_SEED,
        timeout_seconds: 1800,
      }),
    );
    const workDir = join(dir, "work");
    // A successful run throws (DUMPED-OK); keep the error, since a real failure
    // lands here too and its stdout carries the oracle's JSON report.
    let oracleError: unknown;
    let stdout = "";
    try {
      const r = await run(
        ORACLE,
        [
          "run",
          "--probe",
          probePath,
          "--work-dir",
          workDir,
          "--factorio",
          INSTALL.root,
          "--version",
          INSTALL.version,
        ],
        { maxBuffer: 256 * 1024 * 1024 },
      );
      stdout = r.stdout;
    } catch (e) {
      oracleError = e;
      stdout = (e as { stdout?: string }).stdout ?? "";
    }
    let report: { provenance?: { buildLine?: string } } = {};
    try {
      report = JSON.parse(stdout) as typeof report;
    } catch {
      // The buildLine check below names the failure.
    }
    const buildLine = report.provenance?.buildLine ?? "";
    let text: string;
    try {
      text = await readFile(join(workDir, "write", "script-output", "oracle-dump.json"), "utf8");
    } catch (e) {
      throw new Error(`${mode}: no dump`, { cause: oracleError ?? e });
    }
    if (!buildLine.includes(`Version: ${INSTALL.version} `)) {
      throw new Error(`${mode}: ran "${buildLine}", wanted ${INSTALL.version}`, {
        cause: oracleError,
      });
    }
    return { d: JSON.parse(text) as Dump, buildLine };
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

function expectSeed(label: string, got: number, want: number): void {
  if (got !== want)
    throw new Error(`${label}: surface seed ${String(got)}, wanted ${String(want)}`);
}

/** Rows of palette letters back to tile names, indexed [y][x] from the region corner. */
function decodeTiles(t: { palette: string[]; rows: string[] }): string[][] {
  return t.rows.map((r) => Array.from(r, (c) => t.palette[c.charCodeAt(0) - 97]));
}

async function main(): Promise<void> {
  const { d, buildLine } = await runOracle("full");
  const { d: n, buildLine: buildLine2 } = await runOracle("noeffect");
  if (buildLine !== buildLine2) throw new Error("the two runs used different builds");

  for (const k of ["asis", "noplants", "noenemy"]) {
    expectSeed(`gleba ${k}`, d.gleba[k].seed, SURFACE_SEEDS.gleba);
  }
  expectSeed("aquilo", d.aquilo.seed, SURFACE_SEEDS.aquilo);
  expectSeed("aquilo-nowells", d.aquiloNoWells.seed, SURFACE_SEEDS.aquilo);
  expectSeed("aquilo-noeffect", n.seed, SURFACE_SEEDS.aquilo);
  for (const c of AQUILO_RESOURCE_CONTROLS) {
    if (d.aquiloNoWells.zeroed[c] !== 0) throw new Error(`control ${c} did not read back as 0`);
  }
  if (d.gleba.noplants.zeroed.gleba_plants !== 0 || d.gleba.noenemy.zeroed.gleba_enemy_base !== 0) {
    throw new Error("a Gleba control did not read back as 0");
  }

  // The effect on/off comparison: the same world, the same wells, tiles read in both.
  if (JSON.stringify(d.wellList) !== JSON.stringify(n.wells)) {
    throw new Error("the wells differ between the two runs, so the worlds differ");
  }
  const withEffect = decodeTiles(d.tilesWithEffect);
  const without = decodeTiles(n.tiles);
  const LO = d.region[0];
  const near = new Set<string>();
  for (const [, wx, wy] of d.wellList as [string, number, number][]) {
    for (let dy = -3; dy <= 3; dy++) {
      for (let dx = -3; dx <= 3; dx++) {
        near.add(`${String(Math.floor(wx) + dx)},${String(Math.floor(wy) + dy)}`);
      }
    }
  }
  let nearDiff = 0;
  let farDiff = 0;
  const nearPairs: Record<string, number> = {};
  const farPairs: Record<string, number> = {};
  const nearTiles = new Set<string>();
  for (let y = 0; y < withEffect.length; y++) {
    for (let x = 0; x < withEffect[y].length; x++) {
      const key = `${String(x + LO)},${String(y + LO)}`;
      const isNear = near.has(key);
      if (isNear) nearTiles.add(key);
      if (withEffect[y][x] !== without[y][x]) {
        const pair = `${without[y][x]}>${withEffect[y][x]}`;
        const bucket = isNear ? nearPairs : farPairs;
        bucket[pair] = (bucket[pair] ?? 0) + 1;
        if (isNear) nearDiff++;
        else farDiff++;
      }
    }
  }
  const effectToggle = {
    wells: d.wellList.length,
    explosionEntitiesWithEffect: d.aquilo.counts.byType.explosion ?? 0,
    explosionEntitiesWithoutEffect: n.counts.byType.explosion ?? 0,
    tilesNearWells7x7: nearTiles.size,
    diffNear: nearDiff,
    diffFar: farDiff,
    pairsNear: nearPairs,
    pairsFar: farPairs,
    wellPositions: d.wellList,
  };

  const fixture = {
    _comment:
      `Ground truth from Factorio ${buildLine.replace(/^Version: /, "")} via factorio-oracle, map seed ${String(MAP_SEED)}, ` +
      "DERIVED surface seeds (Gleba 3215206427, Aquilo 3111923328), no terrain-only mod. Region: chunks " +
      `-${String(CHUNKS)}..${String(CHUNKS)} around the origin, entities and tiles read over tiles ${String(d.region[0])}..${String(d.region[1])}. ` +
      "gleba.asis/noplants/noenemy: settings tables and entity counts with gleba_plants or gleba_enemy_base at size 0. " +
      "byControl: every entity prototype with an autoplace table, grouped by its autoplace.control. " +
      "aquilo: settings and entity census. effectToggle: the CLEAN well test - the same Aquilo world generated twice, once " +
      "as shipped and once with created_effect removed from the three resources in data-final-fixes, every region tile " +
      "compared, split into tiles within 3 of a well (7x7) and the rest; wells are asserted identical in both runs. " +
      "aquiloNoWells/wellRewrite: the brief's size-0 control, CONFOUNDED - the resource spots feed aquilo_island_peaks, so " +
      "size 0 reshapes the islands; diffFar there is terrain change, not well rewrite. positiveControl: a well created by " +
      "script on the size-0 surface, tiles read before and after. " +
      "Regenerate: node --experimental-strip-types scripts/probes/planet-autoplace/capture.ts",
    _factorioVersion: INSTALL.version,
    _buildLine: buildLine,
    _crossChecked: false,
    mapSeed: MAP_SEED,
    surfaceSeeds: SURFACE_SEEDS,
    region: d.region,
    gleba: d.gleba,
    aquilo: d.aquilo,
    byControl: d.byControl,
    resourcePrototypes: d.resourcePrototypes,
    effectToggle,
    aquiloNoWells: d.aquiloNoWells,
    wellRewrite: d.wellRewrite,
    tileCensus: d.tileCensus,
    positiveControl: d.positiveControl,
  };
  await writeFile(OUT, JSON.stringify(fixture, null, 2) + "\n");
  console.log(`wrote ${OUT}\n  ${buildLine}`);
  for (const k of ["asis", "noplants", "noenemy"]) {
    console.log(`gleba ${k}`, JSON.stringify(d.gleba[k].counts.byType));
  }
  console.log("aquilo", JSON.stringify(d.aquilo.counts.byType));
  console.log("effectToggle", JSON.stringify({ ...effectToggle, wellPositions: undefined }));
  console.log("size-0 control diffNear/diffFar", d.wellRewrite.diffNear, d.wellRewrite.diffFar);
}

await main();
