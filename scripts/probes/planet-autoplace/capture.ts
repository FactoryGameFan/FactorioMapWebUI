/**
 * What do Gleba and Aquilo put on the ground, and does an Aquilo well rewrite
 * the tiles around it during map generation?
 *
 *   node --experimental-strip-types scripts/probes/planet-autoplace/capture.ts
 *
 * Run from the repository root. Needs the 2.1.23 headless install named in
 * `INSTALL` and writes `test/fixtures/oracle-planet-autoplace.2.1.23.json`.
 * Read `README.md` beside this file for what it found.
 *
 * ## Three questions
 *
 * (a) Gleba's own entity list names only stone and two stromatolites, yet plants
 *     and pentapod nests appear. Do they enter through their autoplace controls
 *     (`gleba_plants`, `gleba_enemy_base`)? Test: generate Gleba three times, once
 *     as is and once each with one of those controls at size 0, and compare the
 *     entity counts. A prototype is listed with its `autoplace.control`, read in
 *     the data stage and carried to the runtime in a `mod-data` prototype.
 * (b) Aquilo has no `cliff_settings` in `planet-map-gen.lua`. Does it get cliffs?
 *     Count `cliff` entities, and dump the surface's `cliff_settings` read back.
 * (c) Aquilo's three resources carry a `created_effect` that sets snow-lumpy,
 *     snow-patchy and ice-rough tiles. Does that run during map generation?
 *
 * ## The (c) comparison, and why it can fail
 *
 * Aquilo is generated twice at the same derived seed: as is, and with the three
 * resource controls at size 0 (so no wells). Every tile in the region is read on
 * both and compared. "0 differing tiles" would be meaningless if no well ever
 * touched the ocean, so the dump also reports, for the as-is surface, how many
 * wells have ammoniacal ocean (or ice and snow) inside their 7x7 and what tiles
 * sit there. Two further controls:
 *
 * - Tiles FAR from every well must be identical on both surfaces, else the
 *   second surface is a different world, not a world without wells.
 * - Positive control: on the no-well surface, a well entity is created by script
 *   on land and on ocean. A script-created entity fires `created_effect`, so if
 *   that changes tiles the apparatus can see a rewrite when one happens.
 */
